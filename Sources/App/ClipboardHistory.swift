import AppKit

/// Everything copied since the app started, newest first. It's kept in memory only, so it's gone
/// when the Mac shuts down or restarts.
@MainActor
final class ClipboardHistory {
    static let limit = 50
    /// Apps mark what they only put on the clipboard for a moment with these, so it stays out of
    /// the history.
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    private(set) var items: [Clip] = []
    private var changeCount = -1
    private var timer: Timer?

    /// macOS doesn't announce clipboard changes, so check the change count a few times a second.
    func start() {
        let timer = Timer(timeInterval: 0.3, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.check() }
        }
        // In the common modes, so copies are still noticed while a menu is open.
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        check()
    }

    private func check() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        if let types = pasteboard.types, !Self.skippedTypes.isDisjoint(with: types) { return }
        guard let clip = Clip(from: pasteboard) else { return }
        add(clip)
    }

    private func add(_ clip: Clip) {
        items.removeAll { $0.isSame(as: clip) }
        items.insert(clip, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// Puts an item back on the clipboard and moves it to the top.
    func copy(_ clip: Clip) {
        let pasteboard = NSPasteboard.general
        clip.write(to: pasteboard)
        changeCount = pasteboard.changeCount
        add(clip)
    }

    func clear() {
        items.removeAll()
    }
}
